/**
 * The hook farm: a directory of hooks Pi owns, under `~/.pi/agent/attribution/hooks`.
 *
 * Nothing is written into a repository. The session's environment points `core.hooksPath` at this
 * directory through `GIT_CONFIG_*`, which is worth one command's process, so the repositories stay
 * exactly as they were and a session that ends leaves no trace behind.
 *
 * The farm has to cover every hook name git may call, because `core.hooksPath` is exclusive: git looks
 * in one directory only, and it looks in ours. A name we do not provide is a repository hook that
 * silently stops running. Each generated hook therefore calls `apply.mjs`, which runs the repository's
 * own hook first and passes its exit status through.
 */

import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SCHEMA } from "./state.ts";

/** Names where a shim that chains and exits 0 cannot change what git does. */
export const CHAINED_HOOKS = [
	"applypatch-msg",
	"commit-msg",
	"post-applypatch",
	"post-checkout",
	"post-commit",
	"post-index-change",
	"post-merge",
	"post-rewrite",
	"pre-applypatch",
	"pre-auto-gc",
	"pre-commit",
	"pre-merge-commit",
	"pre-push",
	"pre-rebase",
	"prepare-commit-msg",
	"reference-transaction",
	"sendemail-validate",
];

/**
 * Names the farm deliberately does not provide. `githooks(5)` treats the receive-side hooks as the
 * push-target's own policy: an `update` hook replaces git's built-in deny checks, and a
 * `push-to-checkout` hook replaces the `receive.denyCurrentBranch=updateInstead` behaviour. A shim that
 * exits 0 there would loosen the repository, so inside a Pi session a repository that declares one of
 * these is reported by `/attribution status` instead.
 */
export const UNSHIMMED_HOOKS: Record<string, string> = {
	"pre-receive": "gates a push before any ref moves",
	update: "replaces git's built-in deny checks on a push target",
	"post-receive": "runs after refs move on a push target",
	"post-update": "runs after refs move on a push target",
	"push-to-checkout": "replaces receive.denyCurrentBranch=updateInstead",
	"proc-receive": "replaces ref advertisement on a push target",
	"fsmonitor-watchman": "drives the file system monitor",
};

export const MARKER = `pi-commit-attribution schema ${SCHEMA}`;

export interface FarmInput {
	applyPath: string;
	home: string;
	configPath: string;
	modelsPath: string;
	/** false installs no chaining block, which leaves the repository's own hooks disabled. */
	chainRepoHooks?: boolean;
}

/**
 * Chaining stays in sh so that a repository's `pre-commit` or `post-commit` costs a few milliseconds
 * rather than a Node start. Only the two message hooks reach Node, and `commit-msg` skips it when
 * `prepare-commit-msg` already wrote the block. Relative `core.hooksPath` values are resolved against
 * the working-tree root, which is what git does: `githooks(5)` says git changes a hook's directory to
 * the top level, or to `$GIT_DIR` for the push-side hooks.
 */
function chainBlock(name: string): string {
	return `
# The repository's own hook for "${name}", which git would not look for while core.hooksPath points here.
top=$(git rev-parse --show-toplevel 2>/dev/null)
common=$(git rev-parse --git-common-dir 2>/dev/null)
case "$common" in /*) ;; *) common="$top/$common" ;; esac
repo_hp=$(git config --file "$common/config" --get core.hooksPath 2>/dev/null)
glob_hp=$(git config --global --get core.hooksPath 2>/dev/null)
rc=0
for dir in "$repo_hp" "$glob_hp" "$GIT_DIR/hooks" "$common/hooks"; do
	[ -n "$dir" ] || continue
	case "$dir" in /*) ;; *) dir="$top/$dir" ;; esac
	if [ -x "$dir/${name}" ]; then
		"$dir/${name}" "$@"
		rc=$?
		break
	fi
done
if [ $rc -ne 0 ]; then exit $rc; fi`;
}

export function hookScript(name: string, input: FarmInput): string {
	const chain = input.chainRepoHooks === false ? "" : chainBlock(name);
	let tail = "exit 0";
	if (name === "prepare-commit-msg") {
		tail = `command -v node >/dev/null 2>&1 || exit 0
node "${input.applyPath}" "${name}" "$@"`;
	} else if (name === "commit-msg") {
		// Usually prepare-commit-msg already wrote the block; an editor that stripped it is what this
		// hook is here for.
		tail = `grep -qi '^Assisted-by:' "$1" 2>/dev/null && exit 0
command -v node >/dev/null 2>&1 || exit 0
node "${input.applyPath}" "${name}" "$@"`;
	}

	return `#!/bin/sh
# ${MARKER}
# Generated by the pi-commit-attribution Pi extension. It runs the hook the repository declares, with
# its arguments and exit status, then adds the attribution trailers. This file belongs to the extension,
# not to the repository: removing the extension removes its reason to exist.
export PI_ATTRIBUTION_HOME="${input.home}"
export PI_ATTRIBUTION_CONFIG="${input.configPath}"
export PI_ATTRIBUTION_MODELS="${input.modelsPath}"
${chain}
${tail}
`;
}

/** Writes the farm. Returns the names whose file was missing or stale. */
export function writeFarm(dir: string, input: FarmInput): string[] {
	mkdirSync(dir, { recursive: true });
	const written: string[] = [];
	for (const name of CHAINED_HOOKS) {
		const path = join(dir, name);
		const script = hookScript(name, input);
		if (existsSync(path) && readFileSync(path, "utf8") === script) continue;
		writeFileSync(path, script, { mode: 0o755 });
		written.push(name);
	}
	return written;
}

export function farmIsCurrent(dir: string, input: FarmInput): boolean {
	return CHAINED_HOOKS.every((name) => {
		const path = join(dir, name);
		return existsSync(path) && readFileSync(path, "utf8") === hookScript(name, input);
	});
}

/** Removes only files carrying our marker, so a directory that already held someone's hooks survives. */
export function removeFarm(dir: string): string[] {
	if (!existsSync(dir)) return [];
	const removed: string[] = [];
	for (const name of CHAINED_HOOKS) {
		const path = join(dir, name);
		if (!existsSync(path)) continue;
		if (!readFileSync(path, "utf8").includes(MARKER)) continue;
		unlinkSync(path);
		removed.push(name);
	}
	return removed;
}

export interface HookInventory {
	/** Hook names the repository has, wherever its configuration points them. */
	declared: string[];
	/** Declared names the farm does not chain, with the reason they matter. */
	unchained: Record<string, string>;
	/** Where each declared hook was found. */
	paths: Record<string, string>;
}

/** What a repository would have run, so `/attribution status` can say what a session changes there. */
export function inventory(declared: Array<{ name: string; path: string }>): HookInventory {
	const paths: Record<string, string> = {};
	const unchained: Record<string, string> = {};
	for (const entry of declared) {
		paths[entry.name] = entry.path;
		if (!CHAINED_HOOKS.includes(entry.name)) unchained[entry.name] = UNSHIMMED_HOOKS[entry.name] ?? "not covered by the farm";
	}
	return { declared: Object.keys(paths), unchained, paths };
}

/** Directories git would look in for this repository's hooks, in the order `apply.mjs` chains them. */
export function repoHookDirs(info: { top?: string; gitDir?: string; commonDir?: string; repoHooksPath?: string; globalHooksPath?: string }): string[] {
	const out: string[] = [];
	for (const value of [info.repoHooksPath, info.globalHooksPath]) {
		if (!value) continue;
		out.push(value.startsWith("/") ? value : info.top ? join(info.top, value) : value);
	}
	for (const dir of [info.gitDir, info.commonDir]) if (dir) out.push(join(dir, "hooks"));
	return out.filter((dir, index, all) => all.indexOf(dir) === index);
}
